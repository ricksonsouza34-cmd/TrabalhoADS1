create table if not exists public.news (
 id bigint generated by default as identity primary key,
 title text not null,
 category text not null check(category in ('Brasil','Mundo','Tecnologia','Esportes')),
 summary text,
 content text not null,
 image text,
 author_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.news enable row level security;
drop policy if exists "news public read" on public.news;
create policy "news public read" on public.news for select using (true);
drop policy if exists "news author insert" on public.news;
create policy "news author insert" on public.news for insert to authenticated with check (auth.uid()=author_id);
drop policy if exists "news author update" on public.news;
create policy "news author update" on public.news for update to authenticated using (auth.uid()=author_id) with check (auth.uid()=author_id);
drop policy if exists "news author delete" on public.news;
create policy "news author delete" on public.news for delete to authenticated using (auth.uid()=author_id);
